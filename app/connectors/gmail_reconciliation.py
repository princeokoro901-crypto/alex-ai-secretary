"""Read-only cross-reference and append-only decisions for uncertain Gmail sends.

This service never retries delivery, changes the Gmail send ledger, or changes an
execution's terminal status. It correlates records only by the trusted execution
ID generated by Alex's execution gateway; legacy attempts without a link remain
unlinked instead of being matched heuristically.
"""
from __future__ import annotations


class GmailExecutionReconciliationService:
    def __init__(self, ledger, execution_journal):
        if ledger is None or not callable(getattr(ledger, "unresolved", None)):
            raise ValueError("A Gmail send ledger is required")
        if execution_journal is None or not callable(getattr(execution_journal, "get", None)):
            raise ValueError("A durable execution journal is required")
        self.ledger = ledger
        self.execution_journal = execution_journal

    def inspect(self, account_id: str, limit: int = 100) -> dict:
        attempts = self.ledger.unresolved(account_id, limit)
        results = []
        counts = {"linked": 0, "unlinked": 0, "missing_execution": 0,
                  "wrong_execution_type": 0, "status_mismatch": 0}
        for attempt in attempts:
            execution_id = attempt.get("execution_id")
            item = {**attempt, "execution_status": None, "mapping_status": None,
                    "reconciliation_count": 0, "latest_reconciliation_outcome": None}
            if not execution_id:
                mapping = "unlinked"
            else:
                execution = self.execution_journal.get(execution_id)
                if execution is None:
                    mapping = "missing_execution"
                elif execution.get("action_type") != "email.send_gmail":
                    mapping = "wrong_execution_type"
                    item["execution_status"] = execution.get("status")
                else:
                    item["execution_status"] = execution.get("status")
                    if execution.get("status") not in {"uncertain", "running"}:
                        mapping = "status_mismatch"
                    else:
                        mapping = "linked"
                    if callable(getattr(self.execution_journal, "reconciliations_for", None)):
                        decisions = self.execution_journal.reconciliations_for(execution_id)
                        item["reconciliation_count"] = len(decisions)
                        if decisions:
                            item["latest_reconciliation_outcome"] = decisions[-1].get("outcome")
            item["mapping_status"] = mapping
            counts[mapping] = counts.get(mapping, 0) + 1
            results.append(item)
        return {
            "attempts": results,
            "counts": counts,
            "note": "Correlation uses only the exact gateway-generated execution ID. This view does not prove delivery, mutate either store, or authorize retries.",
        }

    def record_decision(self, account_id: str, attempt_id: str, outcome: str,
                        reason: str, actor: dict, external_reference: str | None = None) -> dict:
        attempt = self.ledger.get_attempt(account_id, attempt_id)
        if attempt is None:
            raise LookupError("Gmail send attempt not found")
        if attempt.get("status") != "uncertain":
            raise ValueError("Only an uncertain Gmail send attempt can be reconciled")
        execution_id = attempt.get("execution_id")
        if not execution_id:
            raise ValueError("This legacy Gmail attempt has no execution link; do not guess a matching execution")
        execution = self.execution_journal.get(execution_id)
        if execution is None:
            raise LookupError("Linked execution record is missing")
        if execution.get("action_type") != "email.send_gmail":
            raise ValueError("Linked execution is not a Gmail send")
        if execution.get("status") != "uncertain":
            raise ValueError("Linked execution is not uncertain; inspect the cross-store status mismatch")
        if not isinstance(reason, str) or not reason.strip() or len(reason.strip()) > 500:
            raise ValueError("A reconciliation reason of 1 to 500 characters is required")
        if any(ord(char) < 32 and char not in "\t" for char in reason):
            raise ValueError("Reconciliation reason contains unsupported control characters")
        if external_reference is not None:
            if not isinstance(external_reference, str) or len(external_reference.strip()) > 200:
                raise ValueError("External evidence reference must be 200 characters or fewer")
            if any(ord(char) < 32 for char in external_reference):
                raise ValueError("External evidence reference contains unsupported control characters")
            external_reference = external_reference.strip() or None
        if outcome in {"confirmed_succeeded", "confirmed_failed"} and not external_reference:
            raise ValueError("A provider-side evidence reference is required for a confirmed outcome")
        record = self.execution_journal.record_reconciliation(
            execution_id, outcome, reason.strip(), actor, external_reference
        )
        # Deliberately do not update the send ledger or execution status here.
        return {"attempt_id": attempt_id, "execution_id": execution_id,
                "reconciliation": record,
                "note": "Decision recorded for audit only. The Gmail send ledger remains blocked; no retry was performed or authorized."}
